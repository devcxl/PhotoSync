package cn.devcxl.photosync.editor.cloud

import java.io.File
import java.io.FileOutputStream
import java.io.IOException
import java.security.GeneralSecurityException
import java.security.InvalidKeyException
import java.security.KeyStore
import javax.crypto.BadPaddingException
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyPermanentlyInvalidatedException
import android.security.keystore.KeyProperties

import timber.log.Timber

/**
 * One BYOK credential profile as persisted by [ByokSecretStore].
 *
 * @property profileId Stable provider/profile key the rest of the app uses to select credentials.
 * @property apiKey Provider API key, or an empty string when the profile only uses a custom auth
 *   header (for example a self-hosted ComfyUI reverse proxy using Basic auth).
 * @property customAuthHeaderName Optional custom authentication header name.
 * @property customAuthHeaderValue Optional custom authentication header value.
 */
data class ByokCredential(
    val profileId: String,
    val apiKey: String = "",
    val customAuthHeaderName: String? = null,
    val customAuthHeaderValue: String? = null
)

/** Why previously stored BYOK secrets can no longer be read and must be re-entered. */
enum class ByokRecoveryReason {
    /** The AndroidKeyStore key was invalidated, deleted or is otherwise unusable. */
    KEY_UNAVAILABLE,

    /** The encrypted blob failed envelope parsing, authentication or payload decoding. */
    CIPHERTEXT_CORRUPT
}

/**
 * Outcome of [ByokSecretStore.load].
 *
 * [RecoveryRequired] is terminal for the stored artifacts: the damaged key alias and ciphertext
 * file have already been deleted, and the caller must ask the user for the secrets again.
 */
sealed interface ByokReadResult {
    /** The stored credential map decrypted successfully. The map may be empty. */
    data class Loaded(val credentials: Map<String, ByokCredential>) : ByokReadResult

    /** No secret blob has been written yet. */
    data object Empty : ByokReadResult

    /** Damaged artifacts were removed; the user must re-enter the BYOK credentials. */
    data class RecoveryRequired(val reason: ByokRecoveryReason) : ByokReadResult

    /** The store could not be read for a transient reason; stored artifacts were left untouched. */
    data object Unavailable : ByokReadResult
}

/** Raw AES-GCM result. The IV is generated by the key backend, never by the caller. */
data class SealedBytes(val iv: ByteArray, val ciphertext: ByteArray)

/**
 * Key/ciphertext seam for [ByokSecretStore].
 *
 * Implementations own the encryption key and produce a fresh random IV per [encrypt] call. The
 * store owns the on-disk envelope format, which keeps envelope, corruption and recovery behaviour
 * testable on a plain JVM without an AndroidKeyStore.
 */
interface KeyCipherBackend {
    /** Encrypts [plaintext] with a fresh random IV. */
    @Throws(GeneralSecurityException::class)
    fun encrypt(plaintext: ByteArray): SealedBytes

    /** Decrypts [ciphertext] using [iv] and returns the authenticated plaintext. */
    @Throws(GeneralSecurityException::class)
    fun decrypt(iv: ByteArray, ciphertext: ByteArray): ByteArray

    /**
     * Permanently deletes the key material so the next [encrypt] starts from a fresh key.
     * Called only after unrecoverable corruption; implementations must not throw.
     */
    fun deleteKey()
}

/**
 * AES-256-GCM backend backed directly by `AndroidKeyStore`.
 *
 * The key is generated with [KeyGenParameterSpec] and is deliberately *not* bound to lock-screen
 * authentication, so background retries and requests made while the device is locked keep working.
 * GCM's randomized-encryption requirement is left at its default: [Cipher.init] is called without
 * an IV and [Cipher.getIV] supplies the Keystore-generated IV.
 */
class AndroidKeyStoreCipherBackend(
    private val keyAlias: String = DEFAULT_KEY_ALIAS
) : KeyCipherBackend {

    override fun encrypt(plaintext: ByteArray): SealedBytes {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, retrieveOrCreateKey())
        val iv = cipher.getIV()
        return SealedBytes(iv = iv.copyOf(), ciphertext = cipher.doFinal(plaintext))
    }

    override fun decrypt(iv: ByteArray, ciphertext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        val spec = GCMParameterSpec(GCM_TAG_BITS, iv)
        cipher.init(Cipher.DECRYPT_MODE, retrieveOrCreateKey(), spec)
        return cipher.doFinal(ciphertext)
    }

    override fun deleteKey() {
        try {
            synchronized(KEY_CREATION_LOCK) {
                val keyStore = loadKeyStore()
                if (keyStore.containsAlias(keyAlias)) {
                    keyStore.deleteEntry(keyAlias)
                }
            }
        } catch (e: GeneralSecurityException) {
            Timber.w("Unable to delete an unusable BYOK key alias (%s)", e.javaClass.simpleName)
        } catch (e: IOException) {
            Timber.w("Unable to open AndroidKeyStore to delete a BYOK key alias (%s)", e.javaClass.simpleName)
        }
    }

    private fun loadKeyStore(): KeyStore =
        KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }

    private fun retrieveOrCreateKey(): SecretKey = synchronized(KEY_CREATION_LOCK) {
        val keyStore = loadKeyStore()
        val entry = if (keyStore.containsAlias(keyAlias)) keyStore.getEntry(keyAlias, null) else null
        if (entry is KeyStore.SecretKeyEntry) {
            entry.secretKey
        } else {
            if (entry != null) {
                // The alias exists with an unexpected type; replace it so encryption can proceed.
                keyStore.deleteEntry(keyAlias)
            }
            generateKey()
        }
    }

    private fun generateKey(): SecretKey {
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        val spec = KeyGenParameterSpec.Builder(
            keyAlias,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setKeySize(KEY_SIZE_BITS)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            // BYOK keys must stay usable while locked and after the lock screen changes.
            .setUserAuthenticationRequired(false)
            .build()
        generator.init(spec)
        return generator.generateKey()
    }

    companion object {
        /** Default alias shared by every BYOK credential profile in this process. */
        const val DEFAULT_KEY_ALIAS = "photosync.byok.v1"

        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val KEY_SIZE_BITS = 256
        private const val GCM_TAG_BITS = 128

        /** Serializes alias creation/deletion across backend instances in this process. */
        private val KEY_CREATION_LOCK = Any()
    }
}

/**
 * Encrypted store for multiple BYOK credential profiles.
 *
 * The credential map is serialized into a compact length-prefixed payload, encrypted with
 * AES-256-GCM and written to `<noBackupFilesDir>/byok/credentials.bin` as
 * `version | ivLength | iv | ciphertext`. `noBackupFilesDir` is always excluded from Auto Backup
 * and OEM device-to-device transfer, so ciphertext never leaves the device without its Keystore key.
 *
 * Every public method performs file and Keystore I/O and **must be called off the main thread**.
 * Reads and writes are serialized within the process.
 *
 * Failure policy:
 * - a malformed envelope, failed GCM authentication or undecodable payload deletes both the
 *   damaged ciphertext and the key alias and returns [ByokReadResult.RecoveryRequired];
 * - a transient read failure returns [ByokReadResult.Unavailable] without deleting anything;
 * - a transient encryption failure makes [save] return a failure without deleting anything, so the
 *   last committed credentials stay readable; only a permanently invalidated key clears them;
 * - no plaintext credential and no ciphertext fragment is ever written to logs or exception text.
 */
class ByokSecretStore internal constructor(
    private val storageDir: File,
    private val cipherBackend: KeyCipherBackend
) {

    /** Creates a store that keeps its ciphertext under the app's `noBackupFilesDir`. */
    constructor(context: Context) : this(
        File(context.noBackupFilesDir, DIRECTORY_NAME),
        AndroidKeyStoreCipherBackend()
    )

    /** Test seam: isolates the `noBackupFilesDir` path from the real AndroidKeyStore. */
    internal constructor(context: Context, cipherBackend: KeyCipherBackend) : this(
        File(context.noBackupFilesDir, DIRECTORY_NAME),
        cipherBackend
    )

    /** Decrypts and returns every stored credential profile. */
    @Synchronized
    fun load(): ByokReadResult {
        val blob = try {
            readBlob()
        } catch (e: IOException) {
            Timber.w("BYOK secret blob could not be read (%s)", e.javaClass.simpleName)
            return ByokReadResult.Unavailable
        } catch (e: SecurityException) {
            Timber.w("BYOK secret storage is not readable (%s)", e.javaClass.simpleName)
            return ByokReadResult.Unavailable
        } ?: return ByokReadResult.Empty

        val envelope = try {
            SecretEnvelope.parse(blob)
        } catch (e: IllegalArgumentException) {
            return recover(ByokRecoveryReason.CIPHERTEXT_CORRUPT, "malformed BYOK envelope")
        }

        val plaintext = try {
            cipherBackend.decrypt(envelope.iv, envelope.ciphertext)
        } catch (e: KeyPermanentlyInvalidatedException) {
            return recover(ByokRecoveryReason.KEY_UNAVAILABLE, "BYOK key was permanently invalidated")
        } catch (e: InvalidKeyException) {
            return recover(ByokRecoveryReason.KEY_UNAVAILABLE, "BYOK key is unusable")
        } catch (e: BadPaddingException) {
            return recover(ByokRecoveryReason.CIPHERTEXT_CORRUPT, "BYOK ciphertext failed authentication")
        } catch (e: GeneralSecurityException) {
            return recover(ByokRecoveryReason.CIPHERTEXT_CORRUPT, "BYOK ciphertext could not be decrypted")
        } catch (e: IOException) {
            Timber.w("BYOK keystore is temporarily unavailable (%s)", e.javaClass.simpleName)
            return ByokReadResult.Unavailable
        } catch (e: RuntimeException) {
            return recover(ByokRecoveryReason.KEY_UNAVAILABLE, "BYOK keystore failed unexpectedly")
        }

        return try {
            ByokReadResult.Loaded(SecretPayload.decode(plaintext))
        } catch (e: IllegalArgumentException) {
            recover(ByokRecoveryReason.CIPHERTEXT_CORRUPT, "BYOK payload is malformed")
        } catch (e: IOException) {
            recover(ByokRecoveryReason.CIPHERTEXT_CORRUPT, "BYOK payload is truncated")
        } finally {
            plaintext.fill(0)
        }
    }

    /**
     * Encrypts and atomically replaces the stored credential map.
     *
     * A transient backend failure never touches the artifacts already on disk: the previous
     * ciphertext and its key alias stay intact so a later [load] can still return the last
     * committed credentials. Only a [KeyPermanentlyInvalidatedException] proves the key can never
     * be used again and therefore triggers the same clean re-entry as a failed [load].
     *
     * @return success once the ciphertext file has been fsynced and renamed into place; failure
     *   with [IllegalArgumentException] for invalid input, or with an [IOException] when the file
     *   could not be written. Secrets are never included in the failure message.
     */
    @Synchronized
    fun save(credentials: Map<String, ByokCredential>): Result<Unit> {
        val validated = try {
            SecretPayload.validate(credentials)
        } catch (e: IllegalArgumentException) {
            return Result.failure(e)
        }

        val payload = SecretPayload.encode(validated)
        try {
            val sealed = try {
                cipherBackend.encrypt(payload)
            } catch (e: KeyPermanentlyInvalidatedException) {
                clearUnrecoverableState()
                Timber.w("BYOK key was permanently invalidated during encryption")
                return Result.failure(IllegalStateException("BYOK keystore is unavailable", e))
            } catch (e: GeneralSecurityException) {
                // Transient: keep the existing ciphertext and alias, the previous credentials remain.
                Timber.w("BYOK keystore rejected an encryption request (%s)", e.javaClass.simpleName)
                return Result.failure(IllegalStateException("BYOK keystore is unavailable", e))
            } catch (e: RuntimeException) {
                // Transient: a failed write must never destroy credentials that are still readable.
                Timber.w("BYOK keystore failed unexpectedly (%s)", e.javaClass.simpleName)
                return Result.failure(IllegalStateException("BYOK keystore is unavailable", e))
            }
            val envelope = SecretEnvelope.write(sealed.iv, sealed.ciphertext)
            writeAtomically(envelope)
            return Result.success(Unit)
        } catch (e: IOException) {
            Timber.w("Failed to persist BYOK secrets (%s)", e.javaClass.simpleName)
            return Result.failure(e)
        } catch (e: SecurityException) {
            Timber.w("BYOK secret storage is not writable (%s)", e.javaClass.simpleName)
            return Result.failure(e)
        } finally {
            payload.fill(0)
        }
    }

    /**
     * Deletes every stored credential profile. The encryption key is kept, so a subsequent save
     * reuses the existing alias.
     */
    @Synchronized
    fun clearAll(): Result<Unit> = try {
        deleteBlob()
        Result.success(Unit)
    } catch (e: IOException) {
        Timber.w("Failed to clear BYOK secrets (%s)", e.javaClass.simpleName)
        Result.failure(e)
    } catch (e: SecurityException) {
        Timber.w("BYOK secret storage is not writable (%s)", e.javaClass.simpleName)
        Result.failure(e)
    }

    private fun readBlob(): ByteArray? {
        val file = blobFile()
        if (!file.isFile) return null
        if (file.length() > MAX_BLOB_BYTES) {
            throw IOException("BYOK secret blob exceeds the supported size")
        }
        return file.readBytes()
    }

    private fun blobFile(): File = File(storageDir, FILE_NAME)

    private fun writeAtomically(envelope: ByteArray) {
        if (!storageDir.isDirectory && !storageDir.mkdirs()) {
            throw IOException("BYOK storage directory is unavailable")
        }
        val temp = File(storageDir, "$FILE_NAME.tmp")
        try {
            FileOutputStream(temp).use { out ->
                out.write(envelope)
                out.flush()
                out.fd.sync()
            }
            if (!temp.renameTo(blobFile())) {
                throw IOException("Could not publish the BYOK secret blob")
            }
        } finally {
            if (temp.exists()) temp.delete()
        }
    }

    private fun recover(reason: ByokRecoveryReason, message: String): ByokReadResult {
        Timber.w("%s; clearing stored BYOK secrets", message)
        clearUnrecoverableState()
        return ByokReadResult.RecoveryRequired(reason)
    }

    /** A key that cannot be used cannot be repaired in place; force a clean re-entry. */
    private fun clearUnrecoverableState() {
        cipherBackend.deleteKey()
        deleteBlobQuietly()
    }

    private fun deleteBlobQuietly() {
        try {
            deleteBlob()
        } catch (e: IOException) {
            Timber.w("Failed to delete a damaged BYOK blob (%s)", e.javaClass.simpleName)
        } catch (e: SecurityException) {
            Timber.w("BYOK secret storage is not writable (%s)", e.javaClass.simpleName)
        }
    }

    @Throws(IOException::class)
    private fun deleteBlob() {
        val file = blobFile()
        if (file.exists() && !file.delete()) {
            throw IOException("Could not delete the BYOK secret blob")
        }
    }

    companion object {
        /** Directory under `noBackupFilesDir` that holds the encrypted BYOK blob. */
        const val DIRECTORY_NAME = "byok"

        /** Name of the encrypted credential file inside [DIRECTORY_NAME]. */
        const val FILE_NAME = "credentials.bin"

        /** Reject absurd files outright instead of loading them into memory. */
        private const val MAX_BLOB_BYTES = 256 * 1024
    }
}
